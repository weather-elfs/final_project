# 6. 공통 평가 함수 (R2, RMSE, MSE, MAE + 저시정 Macro-F1, CSI)
FOG_THRESHOLD = 1.0

def evaluate_ppt_metrics(y_true, y_pred, is_visibility=False):
    mse = mean_squared_error(y_true, y_pred)
    rmse = np.sqrt(mse)
    mae = mean_absolute_error(y_true, y_pred)
    r2 = r2_score(y_true, y_pred)
    res = {
        "R2": round(r2, 4),
        "RMSE": round(rmse, 4),
        "MSE": round(mse, 4),
        "MAE": round(mae, 4),
    }
    if is_visibility:
        true_fog = (np.asarray(y_true) < FOG_THRESHOLD).astype(int)
        pred_fog = (np.asarray(y_pred) < FOG_THRESHOLD).astype(int)
        macro_f1 = f1_score(true_fog, pred_fog, average="macro", zero_division=0)
        tp = np.sum((true_fog == 1) & (pred_fog == 1))
        fp = np.sum((true_fog == 0) & (pred_fog == 1))
        fn = np.sum((true_fog == 1) & (pred_fog == 0))
        csi = tp / (tp + fp + fn) if (tp + fp + fn) > 0 else 0.0
        res["Macro-F1"] = round(macro_f1, 4)
        res["CSI"] = round(csi, 4)
    else:
        res["Macro-F1"] = np.nan
        res["CSI"] = np.nan
    return res

